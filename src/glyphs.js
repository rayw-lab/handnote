// 坐标单位 = 字号 em；原点在字的左侧基线，x 向右、y 向下（基线以上为负）。
//   汉字：hanzi-writer-data 的笔画中线（medians，源自 Make Me a Hanzi，9580 字）
//   拉丁字母 / 数字 / 符号：EMS Tech 单线字体（hersheytext，SIL OFL），再补几个手画符号

import { assets } from './config.js';

const HZ_BASE = 0.88;           // 汉字 em 框底部到基线的位置（框内 0..1，基线在 0.88）
const LATIN_K = 1.1;            // EMS 字体 cap-height=500/1000，放大到大写高约 0.55em
const hzCache = new Map();
let latin = null;

export async function loadLatin(font = 'EMSTech') {
  if (latin) return latin;
  const src = await (await fetch(assets.latin(font))).text();
  latin = {};
  for (const m of src.matchAll(/<glyph unicode="([^"]*)"[^>]*?horiz-adv-x="([\d.]+)"(?:[^>]*?d="([^"]*)")?/g)) {
    const u = m[1].replace(/&#x([0-9a-f]+);/i, (_, h) => String.fromCodePoint(parseInt(h, 16)))
      .replace('&amp;', '&').replace('&quot;', '"').replace('&lt;', '<').replace('&gt;', '>');
    latin[u] = { adv: (+m[2] / 1000) * LATIN_K, strokes: parsePath(m[3] || '', LATIN_K / 1000) };
  }
  Object.assign(latin, extraSymbols());
  return latin;
}

function parsePath(d, k) {
  const strokes = [];
  let cur = null;
  for (const m of d.matchAll(/([ML])\s*(-?[\d.]+)\s+(-?[\d.]+)/g)) {
    const p = [+m[2] * k, -(+m[3]) * k];
    if (m[1] === 'M') { cur = [p]; strokes.push(cur); } else cur.push(p);
  }
  return strokes;  // 单点笔画保留：句点、冒号的点
}

