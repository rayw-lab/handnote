function circle(cx, cy, r, n = 14) {
  return Array.from({ length: n + 2 }, (_, i) => {
    const a = (i / n) * Math.PI * 2 - 1.8;
    return [cx + r * Math.cos(a), cy + r * Math.sin(a)];
  });
}

export async function loadHanzi(ch) {
  if (hzCache.has(ch)) return hzCache.get(ch);
  const r = await fetch(assets.hanzi(ch));
  if (!r.ok) throw new Error(`No stroke data for ${ch} (缺少笔画数据)`);
  const d = await r.json();
  const g = {
    adv: 0.86,
    hanzi: true,
    strokes: d.medians.map((m) => m.map(([x, y]) => [x / 1024 - 0.07, (900 - y) / 1024 - HZ_BASE])),
  };
  hzCache.set(ch, g);
  return g;
}

const isHan = (c) => /\p{Script=Han}/u.test(c);
const FULLWIDTH = { '：': ':', '，': ',', '（': '(', '）': ')', '；': ';', '！': '!', '？': '?' };

// 中文标点用拉丁笔画近似，并保留全角宽度
export async function glyph(ch) {
  if (isHan(ch)) return loadHanzi(ch);
  const lat = await loadLatin();
  if (FULLWIDTH[ch]) {
    const g = lat[FULLWIDTH[ch]];
    return { adv: 0.9, strokes: g.strokes.map((s) => s.map(([x, y]) => [x + 0.25, y])) };
  }
  const circled = '①②③④⑤⑥⑦⑧⑨'.indexOf(ch);
  if (circled >= 0) {
    // 圈码：手画一个圈，里面写数字
    const d = lat[String(circled + 1)], k = 0.62;
    const db = d.strokes.flat(), x0 = Math.min(...db.map((p) => p[0])), x1 = Math.max(...db.map((p) => p[0]));
    const y0 = Math.min(...db.map((p) => p[1])), y1 = Math.max(...db.map((p) => p[1]));
    const ox = 0.42 - ((x0 + x1) / 2) * k, oy = -0.38 - ((y0 + y1) / 2) * k;
    return { adv: 0.9, strokes: [circle(0.42, -0.38, 0.36, 18), ...d.strokes.map((st) => st.map(([x, y]) => [ox + x * k, oy + y * k]))] };
  }
  // 罗马数字：带上下横，留足宽度（窄的 I 紧贴汉字会被吞掉）
  if (ch === 'Ⅰ' || ch === 'Ⅱ') {
    const n = ch === 'Ⅰ' ? 1 : 2, w = 0.16 + 0.14 * n, st = [[[0.08, -0.55], [0.08 + w, -0.55]], [[0.08, 0], [0.08 + w, 0]]];
    for (let i = 0; i < n; i++) { const x = 0.08 + w * ((i + 1) / (n + 1)); st.push([[x, -0.55], [x, 0]]); }
    return { adv: w + 0.16, strokes: st };
  }
  if (ch === '　') return { adv: 0.9, strokes: [] };  // 全角空格：对齐用
  if (ch === '。') return { adv: 0.9, strokes: [circle(0.2, -0.06, 0.07)] };
  if (ch === '、') return { adv: 0.9, strokes: [[[0.14, -0.16], [0.3, 0.02]]] };
  if (ch === 'ϕ') return glyph('φ');   // \phi 与 \varphi 同形
  const g = lat[ch];
  if (!g) throw new Error(`No glyph for ${ch} U+${ch.codePointAt(0).toString(16)} (缺少字形)`);
  return g;
}
